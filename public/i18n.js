let language = 'ko';

export function setLanguage(value) {
  language = value === 'en' || value === 'ja' ? value : 'ko';
  return language;
}

export function t(key, values) {
  const pair = Object.hasOwn(copy, key) ? copy[key] : undefined;
  const text = language === 'en' ? pair?.[0] ?? key : language === 'ja' ? pair?.[1] ?? key : key;
  return values ? text.replace(/\{(\w+)\}/g, (marker, name) => values[name] ?? marker) : text;
}

export function localizeStatic(root) {
  const text = [];
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    const key = node.nodeValue.trim();
    if (Object.hasOwn(copy, key)) text.push({ node, key, value: node.nodeValue });
  }
  const attributes = [];
  for (const node of root.querySelectorAll('[aria-label], [placeholder], [alt]')) {
    for (const name of ['aria-label', 'placeholder', 'alt']) {
      const key = node.getAttribute(name);
      if (Object.hasOwn(copy, key)) attributes.push({ node, name, key });
    }
  }
  return () => {
    for (const { node, key, value } of text) node.nodeValue = value.replace(key, t(key));
    for (const { node, name, key } of attributes) node.setAttribute(name, t(key));
  };
}
